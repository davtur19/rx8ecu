def spec_mirror(r4, r5, r6, r7, ram, fr_in):
    """pc-interpreter over CODE; returns ("RET", regs, writes, ram, pr,
    fr_bits, fpul) or ("SKIP"/"ERR", detail).  fr_in is 16 uint32 bit
    patterns; fr is the float32 mirror (bits2f) the FPU fragments run
    on — sh2emu semantics, exact same list the emulator builds from
    ts(v) in call()."""
    global _WRITES
    _WRITES[:] = []
    r = [0] * 16
    r[4], r[5], r[6], r[7] = r4 & 0xFFFFFFFF, r5 & 0xFFFFFFFF, r6 & 0xFFFFFFFF, r7 & 0xFFFFFFFF
    r[15] = STACK_TOP & 0xFFFFFFFF
    fr = [bits2f(x) for x in fr_in]
    ns = {"r": r, "T": 0, "Q": 0, "M": 0, "mach": 0, "macl": 0, "pr": 0xEEEE0000,
          "sr": 0x000000F0,  # sh2emu call() default (independent of T)
          "fr": fr, "fpul": 0, "fpscr": 0,
          "s8": s8, "s16": s16, "s32": s32, "ts": ts, "bits2f": bits2f,
          "f2bits": f2bits, "ram": ram, "sp": r[15],
          "local": {off: _rdw(ram, STACK_BASE + off, 4) for off in STACK_OFFS},
          "_rdw": _rdw, "_wrw": _wrw, "STACK_BASE": STACK_BASE}
    pc = ENTRY
    steps = 0
    while True:
        steps += 1
        if steps > MAXSTEPS:
            return ("SKIP", None)
        inst = CODE.get(pc)
        if inst is None:
            return ("ERR", pc)
        kind = inst["kind"]
        if kind == "branch":
            t = ns["T"]
            cond = inst["cond"]
            taken = True
            if cond == "T":
                taken = (t == 1)
            elif cond == "notT":
                taken = (t == 0)
            slot_py = inst["slot_py"]
            if slot_py:
                exec(slot_py, ns)
            if taken:
                pc = inst["target"]
            elif slot_py is not None:
                pc = pc + 4            # delayed: slot at P+2 already ran
            else:
                pc = pc + 2            # non-delayed bt/bf
        elif kind == "dynbranch":
            slot_py = inst["slot_py"]
            if slot_py:
                exec(slot_py, ns)
            if inst["set_pr"]:
                ns["pr"] = (pc + 4) & 0xFFFFFFFF
            pc = (pc + 4 + ns["r"][inst["reg"]]) & 0xFFFFFFFF
        elif kind == "ret":
            slot_py = inst["slot_py"]
            if slot_py:
                exec(slot_py, ns)
            r[15] = ns["sp"] & 0xFFFFFFFF
            return ("RET", [x & 0xFFFFFFFF for x in r], _WRITES, ram,
                    ns["pr"] & 0xFFFFFFFF,
                    [f2bits(f) for f in fr], ns["fpul"] & 0xFFFFFFFF)
        else:
            py = inst["py"]
            if py:
                exec(py, ns)
            pc = pc + 2

def run(cpu, ram, a, b, c_, d, fr_in):
    ram = dict(ram)
    ram[SENT] = 0x00; ram[SENT + 1] = 0x0B; ram[SENT + 2] = 0x00; ram[SENT + 3] = 0x09
    cpu.call(ENTRY, r4=a, r5=b, r6=c_, r7=d, ram=ram,
             fr={i: bits2f(fr_in[i]) for i in range(16)},
             regs={15: STACK_TOP}, max_steps=MAXSTEPS)
    out = dict(cpu.ram)
    for i in range(4):
        out.pop(SENT + i, None)
    return (cpu.r[0] & 0xFFFFFFFF, [x & 0xFFFFFFFF for x in cpu.r], out,
            cpu.pr & 0xFFFFFFFF,
            [f2bits(cpu.fr[i]) for i in range(16)], cpu.fpul & 0xFFFFFFFF)

