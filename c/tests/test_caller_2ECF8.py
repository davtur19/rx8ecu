def spec_mirror(r4, r5, r6, r7, ram):
    global _WRITES
    _WRITES[:] = []
    r = [0] * 16
    r[4], r[5], r[6], r[7] = r4 & 0xFFFFFFFF, r5 & 0xFFFFFFFF, r6 & 0xFFFFFFFF, r7 & 0xFFFFFFFF
    r[15] = STACK_TOP & 0xFFFFFFFF
    fr = [0.0] * 16
    ns = {"r": r, "fr": fr, "T": 0, "Q": 0, "M": 0, "mach": 0, "macl": 0, "pr": PRET,
          "sr": 0x000000F0, "gbr": 0, "s8": s8, "s16": s16, "s32": s32, "ts": ts,
          "bits2f": bits2f, "f2bits": f2bits, "ram": ram,
          "sp": r[15], "_rdw": _rdw, "_wrw": _wrw, "STACK_BASE": STACK_BASE,
          "local": {off: _rdw(ram, STACK_BASE + off, 4) for off in STACK_OFFS}}
    pc = ENTRY
    steps = 0
    while True:
        # (v8.8) keep r[15] in lockstep with the runtime `sp` alias.  The
        # stack opcodes (sts.l pr,@-r15 / add #imm,r15 / mov.l @r15+,Rn)
        # are emitted sp-relative (sp updates only); any instruction that
        # COPIES r15 into another register (frame ptr / wrapper arg, e.g.
        # mov r15,r4) would otherwise read a stale r[15] one push ahead of
        # sp, making the callee store/load the WRONG stack slot (MISMATCH
        # case=0 reg=r0/r2/r3/r4 on caller wrappers).
        r[15] = ns["sp"] & 0xFFFFFFFF
        steps += 1
        if steps > MAXSTEPS:
            return ("SKIP", None)
        inst = CODE.get(pc)
        if inst is None:
            return ("RET", [x & 0xFFFFFFFF for x in r], list(_WRITES), dict(ram),
                    ns["pr"] & 0xFFFFFFFF)
        kind = inst["kind"]
        if kind == "jt":
            slot_py = inst["slot_py"]
            if slot_py:
                exec(slot_py, ns)
            reg = inst["reg"]; base = inst["base"]
            tgt = _rdw(ram, (base + r[reg]) & 0xFFFFFFFF, 4)
            if tgt not in inst["cases"]:
                return ("ERR", pc)      # table miss -> FAIL (mirror default)
            pc = tgt
        elif kind == "call":
            if inst["set_pr"]:
                ns["pr"] = inst["ret_pc"]
            slot_py = inst["slot_py"]
            if slot_py:
                exec(slot_py, ns)
            pc = inst["target"]
        elif kind == "branch":
            t = ns["T"]
            taken = True
            if inst["cond"] == "T":
                taken = (t == 1)
            elif inst["cond"] == "notT":
                taken = (t == 0)
            slot_py = inst["slot_py"]
            if slot_py:
                exec(slot_py, ns)
            pc = inst["target"] if taken else (pc + 4 if slot_py is not None else pc + 2)
        elif kind == "ret":
            slot_py = inst["slot_py"]
            if slot_py:
                exec(slot_py, ns)
            r[15] = ns["sp"] & 0xFFFFFFFF
            pc = ns["pr"] & 0xFFFFFFFF
        else:
            py = inst["py"]
            if py:
                exec(py, ns)
            pc = pc + 2

def run(cpu, ram, a, b, c_, d):
    ram = dict(ram)
    cpu.call(ENTRY, r4=a, r5=b, r6=c_, r7=d, ram=ram, regs={15: STACK_TOP},
             max_steps=MAXSTEPS)
    return cpu.r[0] & 0xFFFFFFFF, [x & 0xFFFFFFFF for x in cpu.r], dict(cpu.ram), cpu.pr & 0xFFFFFFFF

def main():
    rnd = random.Random(SEED)
    cpu = SH2(ROM_BYTES)
    skipped = 0
    for caso in range(N):
        ram = {}
        if RAM_MIN is not None:
            for a in range(RAM_MIN - 0x400, RAM_MAX + 0x401):
                ram[a] = (a * 0x9E3779B1 + caso * 0x10003) & 0xFF
        for a in range(STACK_BASE, STACK_BASE + 0x400):
            ram[a] = (a * 0x9E3779B1 + caso * 0x10003) & 0xFF
        a = rnd.randint(0, 0xFFFFFFFF); b = rnd.randint(0, 0xFFFFFFFF)
        c_ = rnd.randint(0, 0xFFFFFFFF); d = rnd.randint(0, 0xFFFFFFFF)
        m = spec_mirror(a, b, c_, d, dict(ram))
        if m[0] != "RET":
            if m[0] == "SKIP":
                try:
                    run(cpu, ram, a, b, c_, d)
                except StepLimitExceeded:
                    continue
                except (NotImplementedError, RuntimeError):
                    skipped += 1; continue
                print("MISMATCH case=%d mirror=SKIP emu=RET" % (caso,))
                sys.exit(1)
            skipped += 1; continue
        try:
            g = run(cpu, ram, a, b, c_, d)
        except (StepLimitExceeded, NotImplementedError, RuntimeError):
            skipped += 1; continue
        _, exp_regs, _, exp_ram, exp_pr = m
        _, got_regs, got_ram, got_pr = g
        for i in range(16):
            if exp_regs[i] != got_regs[i]:
                print("MISMATCH case=%d reg=r%d mirror=%08X emu=%08X" % (caso, i, exp_regs[i], got_regs[i]))
                sys.exit(1)
        if exp_pr != got_pr:
            print("MISMATCH case=%d reg=pr mirror=%08X emu=%08X" % (caso, exp_pr, got_pr))
            sys.exit(1)
        for ad in sorted(set(exp_ram) | set(got_ram)):
            if exp_ram.get(ad, 0) != got_ram.get(ad, 0):
                print("MISMATCH case=%d addr=0x%08X mirror=%02X emu=%02X" % (caso, ad, exp_ram.get(ad, 0), got_ram.get(ad, 0)))
                sys.exit(1)
    ok = N - skipped
    has_ret = False
    seen = set(); stack = [ENTRY]
    while stack:
        pc = stack.pop()
        if pc in seen:
            continue
        seen.add(pc)
        inst = CODE.get(pc)
        if inst is None:
            continue
        k = inst["kind"]
        if k == "ret":
            has_ret = True; break
        if k == "branch":
            if inst["target"] is not None:
                stack.append(inst["target"])
            stack.append(pc + (4 if inst["slot_py"] is not None else 2))
        elif k == "call":
            stack.append(inst["ret_pc"])
        elif k == "jt":
            stack.extend(c for c in inst["cases"] if c is not None)
            stack.append(pc + (4 if inst["slot_py"] is not None else 2))
        elif k == "dynbranch":
            stack.append(pc + (4 if inst["slot_py"] is not None else 2))
        else:
            stack.append(pc + 2)
    if ok == 0 and not has_ret:
        print("HALT (correct) %d/%d (skipped=%d)" % (ok, N, skipped))
        sys.exit(0)
    if skipped > 200 or ok == 0:
        print("FAIL %d/%d (skipped=%d)" % (ok, N, skipped))
        sys.exit(1)
    print("PASS %d/%d (skipped=%d)" % (ok, N, skipped))

if __name__ == "__main__":
    main()
