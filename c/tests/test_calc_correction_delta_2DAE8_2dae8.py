def spec_mirror(r4, r5, r6, r7, ram, fr_in):
    """pc-interpreter over CODE; returns ("RET", regs, writes, ram, pr,
    fr_bits, fpul) or ("SKIP"/"ERR", detail).  fr_in is 16 uint32 bit
    patterns; fr is the float32 mirror (bits2f) the FPU fragments run
    on — sh2emu semantics, exact same list the emulator builds from
    ts(v) in call()."""
    global _WRITES
    _WRITES[:] = []
    r = [0] * 16
    r[4], r[5], r[6], r[7] = r4 & 0xFFFFFFFF, r5 & 0xFFFFFFFF, r6 & 0xFFFFFFFF, r7 & 0xFFFFFFFF
    r[15] = STACK_TOP & 0xFFFFFFFF
    fr = [bits2f(x) for x in fr_in]
    ns = {"r": r, "T": 0, "Q": 0, "M": 0, "mach": 0, "macl": 0, "pr": 0xEEEE0000,
          "fr": fr, "fpul": 0, "fpscr": 0,
          "s8": s8, "s16": s16, "s32": s32, "ts": ts, "bits2f": bits2f,
          "f2bits": f2bits, "ram": ram, "sp": r[15],
          "local": {off: _rdw(ram, STACK_BASE + off, 4) for off in STACK_OFFS},
          "_rdw": _rdw, "_wrw": _wrw, "STACK_BASE": STACK_BASE}
    pc = ENTRY
    steps = 0
    while True:
        steps += 1
        if steps > MAXSTEPS:
            return ("SKIP", None)
        inst = CODE.get(pc)
        if inst is None:
            return ("ERR", pc)
        kind = inst["kind"]
        if kind == "branch":
            t = ns["T"]
            cond = inst["cond"]
            taken = True
            if cond == "T":
                taken = (t == 1)
            elif cond == "notT":
                taken = (t == 0)
            slot_py = inst["slot_py"]
            if slot_py:
                exec(slot_py, ns)
            if taken:
                pc = inst["target"]
            elif slot_py is not None:
                pc = pc + 4            # delayed: slot at P+2 already ran
            else:
                pc = pc + 2            # non-delayed bt/bf
        elif kind == "ret":
            slot_py = inst["slot_py"]
            if slot_py:
                exec(slot_py, ns)
            r[15] = ns["sp"] & 0xFFFFFFFF
            return ("RET", [x & 0xFFFFFFFF for x in r], _WRITES, ram,
                    ns["pr"] & 0xFFFFFFFF,
                    [f2bits(f) for f in fr], ns["fpul"] & 0xFFFFFFFF)
        else:
            py = inst["py"]
            if py:
                exec(py, ns)
            pc = pc + 2

def run(cpu, ram, a, b, c_, d, fr_in):
    ram = dict(ram)
    ram[SENT] = 0x00; ram[SENT + 1] = 0x0B; ram[SENT + 2] = 0x00; ram[SENT + 3] = 0x09
    cpu.call(ENTRY, r4=a, r5=b, r6=c_, r7=d, ram=ram,
             fr={i: bits2f(fr_in[i]) for i in range(16)},
             regs={15: STACK_TOP}, max_steps=MAXSTEPS)
    out = dict(cpu.ram)
    for i in range(4):
        out.pop(SENT + i, None)
    return (cpu.r[0] & 0xFFFFFFFF, [x & 0xFFFFFFFF for x in cpu.r], out,
            cpu.pr & 0xFFFFFFFF,
            [f2bits(cpu.fr[i]) for i in range(16)], cpu.fpul & 0xFFFFFFFF)

def main():
    rnd = random.Random(SEED)
    cpu = SH2(ROM_BYTES)
    skipped = 0
    for caso in range(N):
        ram = {}
        if RAM_MIN is not None:
            for a in range(RAM_MIN - 0x400, RAM_MAX + 0x401):
                ram[a] = (a * 0x9E3779B1 + caso * 0x10003) & 0xFF
        for a in range(STACK_BASE, STACK_BASE + 0x400):
            ram[a] = (a * 0x9E3779B1 + caso * 0x10003) & 0xFF
        a = rnd.randint(0, 0xFFFFFFFF)
        b = rnd.randint(0, 0xFFFFFFFF)
        c_ = rnd.randint(0, 0xFFFFFFFF)
        d = rnd.randint(0, 0xFFFFFFFF)
        fr_in = [((caso * 0x9E3779B1 + i * 0x1000003) & 0xFFFFFFFF) for i in range(16)]
        fr_in = [((x & 0x7F7FFFFF) | 0x3F800000) for x in fr_in]  # finite, positive, no NaN/Inf
        try:
            m = spec_mirror(a, b, c_, d, dict(ram), fr_in)
        except ValueError:
            skipped += 1          # fsqrt of a negative input (both sides)
            continue
        if m[0] != "RET":
            skipped += 1
            continue
        try:
            g = run(cpu, ram, a, b, c_, d, fr_in)
        except (StepLimitExceeded, NotImplementedError, RuntimeError, ValueError):
            skipped += 1
            continue
        _, exp_regs, _, exp_ram, exp_pr, exp_fr, exp_fpul = m
        _, got_regs, got_ram, got_pr, got_fr, got_fpul = g
        for i in range(16):
            if exp_regs[i] != got_regs[i]:
                print("MISMATCH case=%d reg=r%d mirror=%08X emu=%08X" % (caso, i, exp_regs[i], got_regs[i]))
                sys.exit(1)
        for i in range(16):
            if exp_fr[i] != got_fr[i]:
                print("MISMATCH case=%d fr%d mirror=%08X emu=%08X" % (caso, i, exp_fr[i], got_fr[i]))
                sys.exit(1)
        if exp_fpul != got_fpul:
            print("MISMATCH case=%d fpul mirror=%08X emu=%08X" % (caso, exp_fpul, got_fpul))
            sys.exit(1)
        if exp_pr != got_pr:
            print("MISMATCH case=%d reg=pr mirror=%08X emu=%08X" % (caso, exp_pr, got_pr))
            sys.exit(1)
        for ad in sorted(set(exp_ram) | set(got_ram)):
            if exp_ram.get(ad, 0) != got_ram.get(ad, 0):
                print("MISMATCH case=%d addr=0x%08X mirror=%02X emu=%02X" % (caso, ad, exp_ram.get(ad, 0), got_ram.get(ad, 0)))
                sys.exit(1)
    ok = N - skipped
    if skipped > 200 or ok == 0:
        print("FAIL %d/%d (skipped=%d)" % (ok, N, skipped))
        sys.exit(1)
    print("PASS %d/%d (skipped=%d)" % (ok, N, skipped))

if __name__ == "__main__":
    main()
