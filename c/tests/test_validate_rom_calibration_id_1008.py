_WRITES = []

def _rd(ram, a):
    a &= 0xFFFFFFFF
    v = ram.get(a)
    if v is not None:
        return v
    return ROM_BYTES[a] if a < len(ROM_BYTES) else 0

def _rdw(ram, a, n):
    a &= 0xFFFFFFFF
    return int.from_bytes(bytes(_rd(ram, (a + i) & 0xFFFFFFFF) for i in range(n)), "big")

def _wrw(ram, a, n, v):
    a &= 0xFFFFFFFF
    for i in range(n):
        ad = (a + i) & 0xFFFFFFFF
        ram[ad] = (v >> (8 * (n - 1 - i))) & 0xFF
        _WRITES.append(ad)

