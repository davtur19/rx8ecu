def spec_mirror(r4, r5, r6, r7, ram):
    global _WRITES
    _WRITES[:] = []
    r = [0] * 16
    r[4], r[5], r[6], r[7] = r4 & 0xFFFFFFFF, r5 & 0xFFFFFFFF, r6 & 0xFFFFFFFF, r7 & 0xFFFFFFFF
    r[15] = STACK_TOP & 0xFFFFFFFF
    ns = {"r": r, "T": 0, "Q": 0, "M": 0, "mach": 0, "macl": 0, "pr": PRET,
          "sr": 0x000000F0, "s8": s8, "s16": s16, "s32": s32, "ram": ram,
          "sp": r[15], "_rdw": _rdw, "_wrw": _wrw, "STACK_BASE": STACK_BASE}
    pc = ENTRY
    steps = 0
    while True:
        steps += 1
        if steps > MAXSTEPS:
            return ("SKIP", None)
        inst = CODE.get(pc)
        if inst is None:
            return ("RET", [x & 0xFFFFFFFF for x in r], list(_WRITES), dict(ram),
                    ns["pr"] & 0xFFFFFFFF)
        kind = inst["kind"]
        if kind == "jt":
            slot_py = inst["slot_py"]
            if slot_py:
                exec(slot_py, ns)
            reg = inst["reg"]; base = inst["base"]
            tgt = _rdw(ram, (base + r[reg]) & 0xFFFFFFFF, 4)
            if tgt not in inst["cases"]:
                return ("ERR", pc)      # table miss -> FAIL (mirror default)
            pc = tgt
        elif kind == "call":
            if inst["set_pr"]:
                ns["pr"] = inst["ret_pc"]
            slot_py = inst["slot_py"]
            if slot_py:
                exec(slot_py, ns)
            pc = inst["target"]
        elif kind == "branch":
            t = ns["T"]
            taken = True
            if inst["cond"] == "T":
                taken = (t == 1)
            elif inst["cond"] == "notT":
                taken = (t == 0)
            slot_py = inst["slot_py"]
            if slot_py:
                exec(slot_py, ns)
            pc = inst["target"] if taken else (pc + 4 if slot_py is not None else pc + 2)
        elif kind == "ret":
            slot_py = inst["slot_py"]
            if slot_py:
                exec(slot_py, ns)
            r[15] = ns["sp"] & 0xFFFFFFFF
            pc = ns["pr"] & 0xFFFFFFFF
        else:
            py = inst["py"]
            if py:
                exec(py, ns)
            pc = pc + 2

def run(cpu, ram, a, b, c_, d):
    ram = dict(ram)
    cpu.call(ENTRY, r4=a, r5=b, r6=c_, r7=d, ram=ram, regs={15: STACK_TOP},
             max_steps=MAXSTEPS)
    return cpu.r[0] & 0xFFFFFFFF, [x & 0xFFFFFFFF for x in cpu.r], dict(cpu.ram), cpu.pr & 0xFFFFFFFF

def main():
    rnd = random.Random(SEED)
    cpu = SH2(ROM_BYTES)
    skipped = 0
    for caso in range(N):
        ram = {}
        if RAM_MIN is not None:
            for a in range(RAM_MIN - 0x400, RAM_MAX + 0x401):
                ram[a] = (a * 0x9E3779B1 + caso * 0x10003) & 0xFF
        for a in range(STACK_BASE, STACK_BASE + 0x400):
            ram[a] = (a * 0x9E3779B1 + caso * 0x10003) & 0xFF
        a = rnd.randint(0, 0xFFFFFFFF); b = rnd.randint(0, 0xFFFFFFFF)
        c_ = rnd.randint(0, 0xFFFFFFFF); d = rnd.randint(0, 0xFFFFFFFF)
        m = spec_mirror(a, b, c_, d, dict(ram))
        if m[0] != "RET":
            skipped += 1; continue
        try:
            g = run(cpu, ram, a, b, c_, d)
        except (StepLimitExceeded, NotImplementedError, RuntimeError):
            skipped += 1; continue
        _, exp_regs, _, exp_ram, exp_pr = m
        _, got_regs, got_ram, got_pr = g
        for i in range(16):
            if exp_regs[i] != got_regs[i]:
                print("MISMATCH case=%d reg=r%d mirror=%08X emu=%08X" % (caso, i, exp_regs[i], got_regs[i]))
                sys.exit(1)
        if exp_pr != got_pr:
            print("MISMATCH case=%d reg=pr mirror=%08X emu=%08X" % (caso, exp_pr, got_pr))
            sys.exit(1)
        for ad in sorted(set(exp_ram) | set(got_ram)):
            if exp_ram.get(ad, 0) != got_ram.get(ad, 0):
                print("MISMATCH case=%d addr=0x%08X mirror=%02X emu=%02X" % (caso, ad, exp_ram.get(ad, 0), got_ram.get(ad, 0)))
                sys.exit(1)
    ok = N - skipped
    if skipped > 200 or ok == 0:
        print("FAIL %d/%d (skipped=%d)" % (ok, N, skipped))
        sys.exit(1)
    print("PASS %d/%d (skipped=%d)" % (ok, N, skipped))

if __name__ == "__main__":
    main()
