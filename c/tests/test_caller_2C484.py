def spec_mirror(r4, r5, r6, r7, ram):
    global _WRITES
    _WRITES[:] = []
    r = [0] * 16
    r[4], r[5], r[6], r[7] = r4 & 0xFFFFFFFF, r5 & 0xFFFFFFFF, r6 & 0xFFFFFFFF, r7 & 0xFFFFFFFF
    r[15] = STACK_TOP & 0xFFFFFFFF
    fr = [0.0] * 16
    ns = {"r": r, "fr": fr, "T": 0, "Q": 0, "M": 0, "mach": 0, "macl": 0, "pr": PRET,
          "sr": 0x000000F0, "gbr": 0, "s8": s8, "s16": s16, "s32": s32, "ts": ts,
          "bits2f": bits2f, "f2bits": f2bits, "ram": ram,
          "sp": r[15], "_rdw": _rdw, "_wrw": _wrw, "STACK_BASE": STACK_BASE,
          "local": {off: _rdw(ram, STACK_BASE + off, 4) for off in STACK_OFFS}}
    pc = ENTRY
    steps = 0
    while True:
        # (v8.8) keep r[15] in lockstep with the runtime `sp` alias.  The
        # stack opcodes (sts.l pr,@-r15 / add #imm,r15 / mov.l @r15+,Rn)
        # are emitted sp-relative (sp updates only); any instruction that
        # COPIES r15 into another register (frame ptr / wrapper arg, e.g.
        # mov r15,r4) would otherwise read a stale r[15] one push ahead of
        # sp, making the callee store/load the WRONG stack slot (MISMATCH
        # case=0 reg=r0/r2/r3/r4 on caller wrappers).
        r[15] = ns["sp"] & 0xFFFFFFFF
        steps += 1
        if steps > MAXSTEPS:
            return ("SKIP", None)
        inst = CODE.get(pc)
        if inst is None:
            return ("RET", [x & 0xFFFFFFFF for x in r], list(_WRITES), dict(ram),
                    ns["pr"] & 0xFFFFFFFF)
        kind = inst["kind"]
        if kind == "jt":
            slot_py = inst["slot_py"]
            if slot_py:
                exec(slot_py, ns)
            reg = inst["reg"]; base = inst["base"]
            tgt = _rdw(ram, (base + r[reg]) & 0xFFFFFFFF, 4)
            if tgt not in inst["cases"]:
                return ("ERR", pc)      # table miss -> FAIL (mirror default)
            pc = tgt
        elif kind == "call":
            if inst["set_pr"]:
                ns["pr"] = inst["ret_pc"]
            slot_py = inst["slot_py"]
            if slot_py:
                exec(slot_py, ns)
            pc = inst["target"]
        elif kind == "call_runtime":
            # RAM/ROM-slot indirect call: the runtime target value is
            # ignored; sh2emu executes the seeded nullsub (clean return)
            # so both sides continue together at ret_pc with pr=pc+4.
            if inst["set_pr"]:
                ns["pr"] = inst["ret_pc"]
            slot_py = inst["slot_py"]
            if slot_py:
                exec(slot_py, ns)
            pc = inst["ret_pc"]
        elif kind == "runtime_dispatch":
            # runtime-indexed jmp/jsr: dispatches to r[reg] if that
            # target was lifted into CODE (in-span); else jsr falls
            # through to ret_pc and jmp returns (RET).  Mirrors
            # sh2emu, which runs the real target on the shared seeded
            # RAM (in-span targets match; out-of-span targets drift,
            # but sh2emu escaping is caught by StepLimitExceeded->skip).
            slot_py = inst["slot_py"]
            if slot_py:
                exec(slot_py, ns)
            reg = inst["reg"]
            _tg = r[reg] & 0xFFFFFFFF
            _tgt = CODE.get(_tg)
            if inst["is_call"]:
                ns["pr"] = inst["ret_pc"]
                pc = inst["ret_pc"] if _tgt is None else _tg
            else:
                if _tgt is None:
                    return ("RET", [x & 0xFFFFFFFF for x in r],
                            list(_WRITES), dict(ram), ns["pr"] & 0xFFFFFFFF)
                pc = _tg
        elif kind == "branch":
            t = ns["T"]
            taken = True
            if inst["cond"] == "T":
                taken = (t == 1)
            elif inst["cond"] == "notT":
                taken = (t == 0)
            slot_py = inst["slot_py"]
            if slot_py:
                exec(slot_py, ns)
            pc = inst["target"] if taken else (pc + 4 if slot_py is not None else pc + 2)
        elif kind == "ret":
            if inst.get("rte"):
                # rte pops PC+SR (8 bytes) off the stack before the
                # delay slot / jump; the mirror returns via pr like rts.
                ns["sp"] = (ns["sp"] + 8) & 0xFFFFFFFF
            slot_py = inst["slot_py"]
            if slot_py:
                exec(slot_py, ns)
            r[15] = ns["sp"] & 0xFFFFFFFF
            pc = ns["pr"] & 0xFFFFFFFF
        else:
            py = inst["py"]
            if py:
                exec(py, ns)
            pc = pc + 2

def run(cpu, ram, a, b, c_, d):
    ram = dict(ram)
    cpu.call(ENTRY, r4=a, r5=b, r6=c_, r7=d, ram=ram, regs={15: STACK_TOP},
             max_steps=MAXSTEPS)
    return cpu.r[0] & 0xFFFFFFFF, [x & 0xFFFFFFFF for x in cpu.r], dict(cpu.ram), cpu.pr & 0xFFFFFFFF

