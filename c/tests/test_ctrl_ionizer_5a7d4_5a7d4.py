import os, random, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from sh2emu import SH2
from c_lift_ops import s8, s16, s32

ROM = os.path.join(ROOT, "roms", "stock", "60E1D400.bin")
ENTRY = 0x5A7D4
RAW = bytes.fromhex("97 60 E6 00 95 5B 7F FC 92 5D")
SEED = 42
N = 2000

def spec_mirror(r4, r5, r6, r7):
    r = [0] * 16
    r[4], r[5], r[6], r[7] = r4 & 0xFFFFFFFF, r5 & 0xFFFFFFFF, r6 & 0xFFFFFFFF, r7 & 0xFFFFFFFF
    T = 0; Q = 0; M = 0; mach = 0; macl = 0; pr = 0xEEEE0000
    ns = {"r": r, "T": T, "Q": Q, "M": M, "mach": mach, "macl": macl, "pr": pr,
          "s8": s8, "s16": s16, "s32": s32}
    # 0x05A7D4: op 0x9760
    r[7] = 0xFFFFD2A4
    # 0x05A7D6: op 0xE600
    r[6] = s8(0x00)
    # 0x05A7D8: op 0x955B
    r[5] = 0xFFFFD28E
    # 0x05A7DA: op 0x7FFC
    r[15] = (r[15] + s8(0xFC)) & 0xFFFFFFFF
    # 0x05A7DC: op 0x925D
    r[2] = 0xFFFFD298
    return ns["r"][0] & 0xFFFFFFFF

def run(cpu, a, b, c_, d):
    # run at the original ROM entry; overlay a synthetic rts(0x000B)+nop
    # right after the pure span so PC-relative literal pools stay intact.
    # pr defaults to SENT -> emulator returns r0.
    end = ENTRY + len(RAW)
    ram = {end: 0x00, end + 1: 0x0B, end + 2: 0x00, end + 3: 0x09}
    return cpu.call(ENTRY, r4=a, r5=b, r6=c_, r7=d, ram=ram)

def main():
    rnd = random.Random(SEED)
    cpu = SH2(open(ROM, "rb").read())
    for _ in range(N):
        a = rnd.randint(0, 0xFFFFFFFF)
        b = rnd.randint(0, 0xFFFFFFFF)
        c_ = rnd.randint(0, 0xFFFFFFFF)
        d = rnd.randint(0, 0xFFFFFFFF)
        exp = spec_mirror(a, b, c_, d)
        got = run(cpu, a, b, c_, d)
        if got != exp:
            print("MISMATCH args=(%08X %08X %08X %08X) mirror=%08X emu=%08X" % (a,b,c_,d,exp,got))
            sys.exit(1)
