import os, random, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from sh2emu import SH2, StepLimitExceeded
from c_lift_ops import s8, s16, s32

ROM = os.path.join(ROOT, "roms", "stock", "60E1D400.bin")
ROM_BYTES = open(ROM, "rb").read()
ENTRY = 0x27EAE
SEED = 42
N = 500
MAXSTEPS = 100000
STACK_BASE = 0xFFFFD000
STACK_TOP = STACK_BASE + 0x400
STACK_OFFS = ()
RAM_MIN = None
RAM_MAX = None
PRET = 0xEEEE0000

_WRITES = []

def _rd(ram, a):
    a &= 0xFFFFFFFF
    v = ram.get(a)
    if v is not None:
        return v
    return ROM_BYTES[a] if a < len(ROM_BYTES) else 0

def _rdw(ram, a, n):
    a &= 0xFFFFFFFF
    return int.from_bytes(bytes(_rd(ram, (a + i) & 0xFFFFFFFF) for i in range(n)), "big")

def _wrw(ram, a, n, v):
    a &= 0xFFFFFFFF
    for i in range(n):
        ad = (a + i) & 0xFFFFFFFF
        ram[ad] = (v >> (8 * (n - 1 - i))) & 0xFF
        _WRITES.append(ad)

CODE = {
    0x27eae: {"kind": 'reg', "py": 'r[4] = 0xFFFF8680', "slot_py": None, "target": None, "cond": None},
    0x27eb0: {"kind": 'reg', "py": 'r[3] = 0x0003EE58', "slot_py": None, "target": None, "cond": None},
    0x27eb2: {"kind": "call", "py": None, "slot_py": 'r[5] = s8(0x00)', "target": 0x3ee58, "ret_pc": 0x27eb6, "set_pr": False, "cond": None},
    0x3ee58: {"kind": 'reg', "py": 'r[3] = r[5] & 0xFF', "slot_py": None, "target": None, "cond": None},
    0x3ee5a: {"kind": 'reg', "py": 'r[3] = (r[3] << 8) & 0xFFFFFFFF', "slot_py": None, "target": None, "cond": None},
    0x3ee5c: {"kind": 'reg', "py": 'r[2] = (~r[5]) & 0xFFFFFFFF', "slot_py": None, "target": None, "cond": None},
    0x3ee5e: {"kind": 'reg', "py": 'r[2] = r[2] & 0xFF', "slot_py": None, "target": None, "cond": None},
    0x3ee60: {"kind": 'reg', "py": 'r[3] = (r[3] + r[2]) & 0xFFFFFFFF', "slot_py": None, "target": None, "cond": None},
    0x3ee62: {"kind": 'mem', "py": '_wrw(ram, r[4], 2, r[3])', "slot_py": None, "target": None, "cond": None},
    0x3ee64: {"kind": "ret", "py": None, "slot_py": 'r[0] = s8(0x00)', "target": None, "cond": None},}

def spec_mirror(r4, r5, r6, r7, ram):
    global _WRITES
    _WRITES[:] = []
    r = [0] * 16
    r[4], r[5], r[6], r[7] = r4 & 0xFFFFFFFF, r5 & 0xFFFFFFFF, r6 & 0xFFFFFFFF, r7 & 0xFFFFFFFF
    r[15] = STACK_TOP & 0xFFFFFFFF
    ns = {"r": r, "T": 0, "Q": 0, "M": 0, "mach": 0, "macl": 0, "pr": PRET,
          "sr": 0x000000F0, "s8": s8, "s16": s16, "s32": s32, "ram": ram,
          "sp": r[15], "_rdw": _rdw, "_wrw": _wrw, "STACK_BASE": STACK_BASE}
    pc = ENTRY
    steps = 0
    while True:
        steps += 1
        if steps > MAXSTEPS:
            return ("SKIP", None)
        inst = CODE.get(pc)
        if inst is None:
            return ("RET", [x & 0xFFFFFFFF for x in r], list(_WRITES), dict(ram),
                    ns["pr"] & 0xFFFFFFFF)
        kind = inst["kind"]
        if kind == "call":
            if inst["set_pr"]:
                ns["pr"] = inst["ret_pc"]
            slot_py = inst["slot_py"]
            if slot_py:
                exec(slot_py, ns)
            pc = inst["target"]
        elif kind == "branch":
            t = ns["T"]
            taken = True
            if inst["cond"] == "T":
                taken = (t == 1)
            elif inst["cond"] == "notT":
                taken = (t == 0)
            slot_py = inst["slot_py"]
            if slot_py:
                exec(slot_py, ns)
            pc = inst["target"] if taken else (pc + 4 if slot_py is not None else pc + 2)
        elif kind == "dynbranch":
            slot_py = inst["slot_py"]
            if slot_py:
                exec(slot_py, ns)
            if inst["set_pr"]:
                ns["pr"] = (pc + 4) & 0xFFFFFFFF
            pc = (pc + 4 + ns["r"][inst["reg"]]) & 0xFFFFFFFF
        elif kind == "ret":
            slot_py = inst["slot_py"]
            if slot_py:
                exec(slot_py, ns)
            r[15] = ns["sp"] & 0xFFFFFFFF
            pc = ns["pr"] & 0xFFFFFFFF
        else:
            py = inst["py"]
            if py:
                exec(py, ns)
            pc = pc + 2

def run(cpu, ram, a, b, c_, d):
    ram = dict(ram)
    cpu.call(ENTRY, r4=a, r5=b, r6=c_, r7=d, ram=ram, regs={15: STACK_TOP},
             max_steps=MAXSTEPS)
    return cpu.r[0] & 0xFFFFFFFF, [x & 0xFFFFFFFF for x in cpu.r], dict(cpu.ram), cpu.pr & 0xFFFFFFFF

def main():
    rnd = random.Random(SEED)
    cpu = SH2(ROM_BYTES)
    skipped = 0
    for caso in range(N):
        ram = {}
        if RAM_MIN is not None:
            for a in range(RAM_MIN - 0x400, RAM_MAX + 0x401):
                ram[a] = (a * 0x9E3779B1 + caso * 0x10003) & 0xFF
        for a in range(STACK_BASE, STACK_BASE + 0x400):
            ram[a] = (a * 0x9E3779B1 + caso * 0x10003) & 0xFF
        a = rnd.randint(0, 0xFFFFFFFF); b = rnd.randint(0, 0xFFFFFFFF)
        c_ = rnd.randint(0, 0xFFFFFFFF); d = rnd.randint(0, 0xFFFFFFFF)
        m = spec_mirror(a, b, c_, d, dict(ram))
        if m[0] != "RET":
            skipped += 1; continue
        try:
            g = run(cpu, ram, a, b, c_, d)
        except (StepLimitExceeded, NotImplementedError, RuntimeError):
            skipped += 1; continue
        _, exp_regs, _, exp_ram, exp_pr = m
        _, got_regs, got_ram, got_pr = g
        for i in range(16):
            if exp_regs[i] != got_regs[i]:
                print("MISMATCH case=%d reg=r%d mirror=%08X emu=%08X" % (caso, i, exp_regs[i], got_regs[i]))
                sys.exit(1)
        if exp_pr != got_pr:
            print("MISMATCH case=%d reg=pr mirror=%08X emu=%08X" % (caso, exp_pr, got_pr))
            sys.exit(1)
        for ad in sorted(set(exp_ram) | set(got_ram)):
            if exp_ram.get(ad, 0) != got_ram.get(ad, 0):
                print("MISMATCH case=%d addr=0x%08X mirror=%02X emu=%02X" % (caso, ad, exp_ram.get(ad, 0), got_ram.get(ad, 0)))
                sys.exit(1)
    ok = N - skipped
    if skipped > 200:
        print("FAIL %d/%d (skipped=%d)" % (ok, N, skipped))
        sys.exit(1)
    print("PASS %d/%d (skipped=%d)" % (ok, N, skipped))

if __name__ == "__main__":
    main()
